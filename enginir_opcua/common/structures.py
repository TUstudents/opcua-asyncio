"""
Custom structures and enumerations from an OPC Binary DataTypeDictionary (OPC 10000-5 v1.05, Annexes B and C).

The DataTypeDictionary is deprecated since OPC UA 1.04; current servers describe their types with the
DataTypeDefinition Attribute, which structures104 reads. This module serves older servers and the
generate-structs command. Only a subset of the OPC Binary type system is supported: StructuredTypes made of
fields of known types, arrays with a LengthField, optional fields with a SwitchField, and EnumeratedTypes.
"""

from __future__ import annotations

import logging
import typing
from collections.abc import Callable
from dataclasses import field, make_dataclass
from enum import Enum, EnumMeta, IntEnum
from typing import IO, TYPE_CHECKING, Any
from xml.etree import ElementTree as ET

from enginir_opcua import ua

from .structures104 import _NUMERIC_TYPES, _default_value_for, clean_name

if TYPE_CHECKING:
    from enginir_opcua import Client, Server
    from enginir_opcua.common.node import Node

_logger = logging.getLogger(__name__)


class EnumType:
    """An EnumeratedType of the dictionary, built as an IntEnum."""

    def __init__(self, name: str) -> None:
        self.name = clean_name(name)
        self.fields: list[EnumeratedValue] = []
        self.typeid: str | None = None

    def __str__(self) -> str:
        return f"EnumType({self.name, self.fields})"

    __repr__ = __str__

    def get_code(self) -> str:
        """Python source of the IntEnum, for generate-structs."""
        code = """

class {0}(IntEnum):

    '''
    {0} EnumInt autogenerated from xml
    '''

""".format(self.name)

        for value in self.fields:
            code += f"    {clean_name(value.Name)} = {value.Value}\n"
        return code

    def build_class(self, env: dict[str, Any]) -> type:
        """The IntEnum class; env is not needed by enumerations."""
        members = {clean_name(value.Name): value.Value for value in self.fields}
        cls = IntEnum(self.name, members)  # type: ignore[misc]
        cls.__doc__ = f"{self.name} EnumInt autogenerated from xml"
        return cls


class EnumeratedValue:
    """One EnumeratedValue; Value must be an integer, as text or int."""

    def __init__(self, name: str, value: str | int) -> None:
        if name == "None":
            name = "None_"
        self.Name = name.replace(" ", "")
        self.Value = int(value)


class Struct:
    """A StructuredType of the dictionary, built as a dataclass."""

    def __init__(self, name: str) -> None:
        self.name = clean_name(name)
        self.fields: list[Field] = []
        self.typeid: str | None = None
        self.option_counter = 0

    def __str__(self) -> str:
        return f"Struct(name={self.name}, fields={self.fields}"

    __repr__ = __str__

    def get_code(self) -> str:
        """Python source of the dataclass, for generate-structs."""
        code = f"""

@dataclass(slots=True)
class {self.name}:

    '''
    {self.name} structure autogenerated from xml
    '''

"""
        for sfield in self._fields_with_encoding():
            uatype = sfield.annotation()
            if sfield.is_optional:
                code += f"    {sfield.name}: Optional[{uatype}] = None\n"
            else:
                uavalue = sfield.value
                if isinstance(uavalue, str) and uavalue.startswith("ua."):
                    uavalue = f"field(default_factory=lambda: {uavalue})"
                code += f"    {sfield.name}:'{uatype}' = {uavalue}\n"
        return code

    def _fields_with_encoding(self) -> list[Field]:
        """
        The fields as encoded: a structure with optional fields starts with the UInt32 'Encoding' mask, the form
        the 1.04 structures use, and the SwitchField fields that make up the mask in the dictionary are left out.
        """
        fields = [sfield for sfield in self.fields if sfield.name != "SwitchField"]
        if self.option_counter > 0:
            encoding = Field("Encoding")
            encoding.uatype = "UInt32"
            fields = [encoding, *fields]
        return fields

    def build_class(self, env: dict[str, Any]) -> type:
        """The dataclass; field types are looked up in env first, then in the ua module."""
        spec: dict[str, tuple[Any, Any]] = {}
        for sfield in self._fields_with_encoding():
            annotation = sfield.resolved_annotation(env)
            if sfield.name == "Encoding":
                spec[sfield.name] = (annotation, None)
            elif sfield.is_optional:
                optional = f"typing.Optional[{annotation}]" if isinstance(annotation, str) else annotation | None
                spec[sfield.name] = (optional, None)
            elif sfield.array:
                spec[sfield.name] = (annotation, field(default_factory=list))
            else:
                spec[sfield.name] = (annotation, _default_for_type(sfield.uatype, env))
        cls = make_dataclass(
            self.name,
            [(name, annotation, default) for name, (annotation, default) in spec.items()],
            namespace={"ua": ua, "typing": typing},
            slots=True,
        )
        cls.__module__ = __name__
        cls.__doc__ = f"{self.name} structure autogenerated from xml"
        return cls


class Field:
    """One field of a Struct; value is the default as Python source, for generate-structs."""

    def __init__(self, name: str) -> None:
        self.name = name
        self.uatype: str | None = None
        self.value: str | None = None
        self.array = False
        self.is_optional = False

    def __str__(self) -> str:
        return f"Field(name={self.name}, uatype={self.uatype})"

    __repr__ = __str__

    def annotation(self) -> str:
        """The annotation as source text; an array of Char is a String."""
        uatype = f"ua.{self.uatype}"
        if self.array:
            uatype = f"list[{uatype}]"
        if uatype == "list[ua.Char]":
            uatype = "ua.String"
        return uatype

    def resolved_annotation(self, env: dict[str, Any]) -> Any:
        """The class from env if the type is defined there, else the annotation as source text."""
        found = env.get(self.uatype or "")
        if not isinstance(found, type):
            return self.annotation()
        return list[found] if self.array else found  # type: ignore[valid-type]


def _lookup_type(name: str, env: dict[str, Any]) -> Any:
    found = env.get(name)
    if isinstance(found, type):
        return found
    return getattr(ua, name, None)


_PLAIN_DEFAULT_TYPES = (
    frozenset(("String", "Guid", "ByteString", "CharArray", "Char", "Boolean", "DateTime")) | _NUMERIC_TYPES
)


def _default_for_type(uatype: str | None, env: dict[str, Any]) -> Any:
    name = uatype or ""
    cls = _lookup_type(name, env)
    if isinstance(cls, type) and issubclass(cls, Enum):
        return next(iter(cls.__members__.values()))
    base_name = cls.__name__ if isinstance(cls, type) else name
    if base_name in _PLAIN_DEFAULT_TYPES:
        return _default_value_for(base_name)
    factory: Callable[[], Any] = lambda: _lookup_type(name, env)()  # noqa: E731
    return field(default_factory=factory)


def _default_code(uatype: str, enums: dict[str, int]) -> str:
    """The default of a field as Python source; the same values _default_for_type gives the built classes."""
    if hasattr(ua, uatype):
        uatype = getattr(ua, uatype).__name__
    if uatype == "String":
        return "ua.String()"
    if uatype == "Guid":
        return "uuid.UUID(int=0)"
    if uatype in ("ByteString", "CharArray", "Char"):
        return "b''"
    if uatype == "Boolean":
        return "False"
    if uatype == "DateTime":
        return "ua.get_win_epoch()"
    if uatype in _NUMERIC_TYPES:
        return f"ua.{uatype}(0)"
    if uatype in enums:
        return f"ua.{uatype}({enums[uatype]})"
    if hasattr(ua, uatype) and issubclass(getattr(ua, uatype), Enum):
        return f"ua.{uatype}.{next(iter(getattr(ua, uatype).__members__))}"
    return f"field(default_factory=lambda: ua.{uatype}())"


def _name_of(element: ET.Element) -> str:
    name = element.get("Name")
    if not name:
        raise ua.UaError(f"The dictionary has a {element.tag} without a Name")
    return name


class StructGenerator:
    """Reads an OPC Binary dictionary into a model and builds classes or Python source from it."""

    def __init__(self) -> None:
        self.model: list[EnumType | Struct] = []

    def make_model_from_string(self, xml: str | bytes) -> None:
        self._make_model(ET.fromstring(xml))

    def make_model_from_file(self, path: str) -> None:
        self._make_model(ET.parse(path).getroot())

    def _make_model(self, root: ET.Element) -> None:
        enums: dict[str, int] = {}
        for child in root:
            if child.tag.endswith("EnumeratedType"):
                intenum = EnumType(_name_of(child))
                for xmlfield in child:
                    if xmlfield.tag.endswith("EnumeratedValue"):
                        intenum.fields.append(EnumeratedValue(_name_of(xmlfield), xmlfield.get("Value") or ""))
                if intenum.fields:
                    enums[intenum.name] = intenum.fields[0].Value
                self.model.append(intenum)

        for child in root:
            if child.tag.endswith("StructuredType"):
                struct = Struct(_name_of(child))
                length_fields = {
                    xmlfield.get("LengthField")
                    for xmlfield in child
                    if xmlfield.tag.endswith("Field") and xmlfield.get("LengthField")
                }
                for xmlfield in child:
                    if not xmlfield.tag.endswith("Field"):
                        continue
                    name = _name_of(xmlfield)
                    _type = (xmlfield.get("TypeName") or "").rpartition(":")[2]
                    if name in length_fields or _type == "Bit":
                        continue
                    sfield = Field(clean_name(name))
                    sfield.uatype = clean_name(_type)
                    if xmlfield.get("SwitchField", "") != "":
                        sfield.is_optional = True
                        struct.option_counter += 1
                    if xmlfield.get("LengthField"):
                        sfield.array = True
                        sfield.value = "field(default_factory=list)"
                    else:
                        sfield.value = _default_code(sfield.uatype, enums)
                    struct.fields.append(sfield)
                self.model.append(struct)

    def save_to_file(self, path: str, register: bool = False) -> None:
        """Write the model as Python source; register adds register_extension_object calls for known type ids."""
        with open(path, "w", encoding="utf-8") as file:
            self._make_header(file)
            for struct in self.model:
                file.write(struct.get_code())
            if register:
                file.write(self._make_registration())

    def _make_registration(self) -> str:
        code = "\n\n"
        for struct in self.model:
            if isinstance(struct, EnumType) or struct.typeid is None:
                continue
            code += (
                f"ua.register_extension_object('{struct.name}',"
                f" ua.NodeId.from_string('{struct.typeid}'), {struct.name})\n"
            )
        return code

    def get_python_classes(self, env: dict[str, Any] | None = None) -> dict[str, Any]:
        """Build the classes of the model into env (a new dict if None) and return it."""
        return _generate_python_class(self.model, env=env)

    def _make_header(self, file: IO[str]) -> None:
        file.write("""
'''
THIS FILE IS AUTOGENERATED, DO NOT EDIT!!!
'''
from __future__ import annotations

import uuid
from dataclasses import dataclass, field
from typing import Union, Optional
from enum import IntEnum

from enginir_opcua import ua
""")

    def set_typeid(self, name: str, typeid: str) -> None:
        """Set the encoding NodeId, as text, of the model element called name."""
        for struct in self.model:
            if struct.name == name:
                struct.typeid = typeid
                return


async def load_type_definitions(
    server: Server | Client, nodes: list[Node] | None = None
) -> tuple[list[StructGenerator], dict[str, Any]]:
    """
    Read the dictionaries in the given DataTypeDictionary variables, or in all of them under 'OPC Binary' except the
    standard 'Opc.Ua' one, build their classes and register them in the type registry of the server or client.
    The classes are built from the parsed names and values; no code from the server is executed.
    """
    if nodes is None:
        nodes = []
        for desc in await server.nodes.opc_binary.get_children_descriptions():
            if desc.BrowseName != ua.QualifiedName("Opc.Ua"):
                nodes.append(server.get_node(desc.NodeId))

    types = server.types
    structs_dict: dict[str, Any] = {}
    generators = []
    for node in nodes:
        xml = await node.read_value()
        generator = StructGenerator()
        generators.append(generator)
        generator.make_model_from_string(xml)
        generator.get_python_classes(structs_dict)

        for ndesc in await node.get_children_descriptions():
            ndesc_node = server.get_node(ndesc.NodeId)
            ref_desc_list = await ndesc_node.get_references(
                refs=ua.ObjectIds.HasDescription, direction=ua.BrowseDirection.Inverse
            )
            if not ref_desc_list:
                continue
            name = clean_name(ndesc.BrowseName.Name)
            if name not in structs_dict:
                _logger.warning("%s is found as child of binary definition node but is not found in xml", name)
                continue
            nodeid = ref_desc_list[0].NodeId
            data_types = await server.get_node(nodeid).get_references(
                refs=ua.ObjectIds.HasEncoding, direction=ua.BrowseDirection.Inverse
            )
            types.register_struct(data_types[0].NodeId if data_types else None, nodeid, structs_dict[name], name)
            generator.set_typeid(name, nodeid.to_string())

    await _register_enums(server, structs_dict)
    return generators, structs_dict


def _generate_python_class(model: list[EnumType | Struct], env: dict[str, Any] | None = None) -> dict[str, Any]:
    if env is None:
        env = {}
    for element in model:
        env[element.name] = element.build_class(env)
    return env


async def _register_enums(server: Server | Client, classes: dict[str, Any]) -> None:
    from enginir_opcua.ua.uatypes import _set_ua_attribute

    enum_nodes = {
        clean_name(desc.BrowseName.Name): desc.NodeId
        for desc in await server.nodes.enum_data_type.get_children_descriptions(refs=ua.ObjectIds.HasSubtype)
    }
    for name, cls in classes.items():
        if not isinstance(cls, EnumMeta):
            continue
        nodeid = enum_nodes.get(name)
        if nodeid is None:
            _set_ua_attribute(name, cls, None)
        elif server.types.find_own(nodeid) is None:
            server.types.register_enum(nodeid, cls, name)


async def load_enums(server: Server | Client, env: dict[str, Any] | None = None, force: bool = False) -> dict[str, Any]:
    """
    Build an IntEnum for every direct subtype of Enumeration from its EnumStrings or EnumValues Property and register
    it in the type registry of the server or client; force rebuilds enumerations that are already registered.
    """
    model: list[EnumType | Struct] = []
    nodeids: dict[str, ua.NodeId] = {}

    for desc in await server.nodes.enum_data_type.get_children_descriptions(refs=ua.ObjectIds.HasSubtype):
        enum_name = desc.BrowseName.Name
        enum_node = server.get_node(desc.NodeId)
        if not force and server.types.find_own(desc.NodeId) is not None:
            _logger.debug("Enum type %s is already registered, ignoring", enum_name)
            continue
        enum_type = None
        for child_desc in await enum_node.get_children_descriptions(refs=ua.ObjectIds.HasProperty):
            child_node = server.get_node(child_desc.NodeId)
            if child_desc.BrowseName.Name == "EnumStrings":
                enum_type = await _get_enum_strings(enum_name, child_node)
            elif child_desc.BrowseName.Name == "EnumValues":
                enum_type = await _get_enum_values(enum_name, child_node)
            else:
                _logger.warning("Unexpected children of node %s: %s", desc, child_desc)
        if enum_type is not None:
            model.append(enum_type)
            nodeids[enum_type.name] = desc.NodeId
    classes = _generate_python_class(model, env=env)
    for element in model:
        server.types.register_enum(nodeids[element.name], classes[element.name], element.name)
    return classes


async def _get_enum_values(name: str, node: Node) -> EnumType:
    enum_type = EnumType(name)
    enum_type.fields = [EnumeratedValue(item.DisplayName.Text, item.Value) for item in await node.read_value()]
    return enum_type


async def _get_enum_strings(name: str, node: Node) -> EnumType:
    enum_type = EnumType(name)
    enum_type.fields = [EnumeratedValue(text.Text, idx) for idx, text in enumerate(await node.read_value())]
    return enum_type
