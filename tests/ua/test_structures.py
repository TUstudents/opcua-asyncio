def test_type_dictionary_classes_are_not_built_from_source(monkeypatch):
    executed_sources = []
    real_exec = builtins.exec

    def recording_exec(source, *args, **kwargs):
        executed_sources.append(str(source))
        return real_exec(source, *args, **kwargs)

    monkeypatch.setattr(builtins, "exec", recording_exec)
    generator = StructGenerator()
    generator.make_model_from_file(EXAMPLE_BSD_PATH)
    env = {}
    generator.get_python_classes(env)
    assert set(env) >= {"ScalarValueDataType", "ArrayValueDataType"}
    assert structures.__name__ == env["ScalarValueDataType"].__module__
    assert not [source for source in executed_sources if "autogenerated from xml" in source]


